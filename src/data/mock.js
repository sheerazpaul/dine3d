export function listRestaurants() {
  return RESTAURANTS;
}

export function listFeaturedProducts(limit = 3) {
  const picks = [];
  for (const restaurant of RESTAURANTS) {
    for (const category of restaurant.categories) {
      for (const product of category.products) {
        if (product.isAvailable) {
          picks.push({ restaurant, product });
        }
      }
    }
  }
  // Bestsellers-first: items with a 3D model surface first, then the rest.
  picks.sort((a, b) => Number(!!b.product.model) - Number(!!a.product.model));
  return picks.slice(0, limit);
}

export function getRestaurant(slug) {
  return RESTAURANTS.find((r) => r.slug === slug);
}

export function getProduct(restaurantSlug, productSlug) {
  const restaurant = getRestaurant(restaurantSlug);
  if (!restaurant) return null;
  for (const category of restaurant.categories) {
    const product = category.products.find((p) => p.slug === productSlug);
    if (product) return { restaurant, category, product };
  }
  return null;
}
